import { cvdDomainColors, domainColors } from "./domain.ts";
import {
  cvdHighContrastThemes,
  cvdThemes,
  highContrastThemes,
  DEFAULT_DENSITY,
  DEFAULT_THEME,
  densities,
  semanticTokens,
  staticTokens,
  themes,
  type ThemeTokens,
} from "./tokens.ts";

const HEADER = "/* Generated by scripts/build-tokens.ts from src/theme/*.ts. Do not edit. */\n\n";

function block(selector: string, vars: Readonly<Record<string, string>>): string {
  const lines = Object.entries(vars).map(([name, value]) => `  --hex-${name}: ${value};`);
  return `${selector} {\n${lines.join("\n")}\n}\n`;
}

function ordered(theme: ThemeTokens): Record<string, string> {
  return Object.fromEntries(semanticTokens.map((token) => [token, theme[token]]));
}

const colorScheme = (theme: string) => (theme.startsWith("light") ? "light" : "dark");

/** semantic.css: one block per resolved theme; the default also on :root. */
export function renderSemanticCss(): string {
  const selectorFor = (name: string) => (name === DEFAULT_THEME ? `:root,\n[data-resolved-theme="${name}"]` : `[data-resolved-theme="${name}"]`);
  const themeBlocks = Object.entries(themes).map(([name, theme]) => block(selectorFor(name), ordered(theme)));
  const schemeBlocks = Object.keys(themes).map((name) => `${selectorFor(name)} {\n  color-scheme: ${colorScheme(name)};\n}\n`);
  // Two attributes outrank the theme block; three outrank both, so the
  // colour-blind palette on high contrast wins over each alone.
  const high = (name: string) => `[data-resolved-theme="${name}"][data-resolved-contrast="high"]`;
  const highBlocks = Object.entries(highContrastThemes).map(([name, theme]) => block(high(name), ordered(theme)));
  const cvdBlocks = Object.entries(cvdThemes).map(([name, tokens]) => block(`[data-resolved-theme="${name}"][data-cvd="on"]`, tokens));
  const cvdHighBlocks = Object.entries(cvdHighContrastThemes).map(([name, tokens]) => block(`${high(name)}[data-cvd="on"]`, tokens));
  return HEADER + [block(":root", staticTokens), ...themeBlocks, ...highBlocks, ...cvdBlocks, ...cvdHighBlocks, ...schemeBlocks].join("\n");
}

/** density.css: one block per density preset; the default also on :root. */
export function renderDensityCss(): string {
  const blocks = Object.entries(densities).map(([name, values]) => {
    const selector = name === DEFAULT_DENSITY ? `:root,\n[data-density="${name}"]` : `[data-density="${name}"]`;
    return block(selector, values);
  });
  return HEADER + blocks.join("\n");
}

/** domain.css: domain colours as plain custom properties. */
export function renderDomainCss(): string {
  return HEADER + [block(":root", domainColors), block('[data-cvd="on"]', cvdDomainColors)].join("\n");
}

export const generatedFiles = {
  "semantic.css": renderSemanticCss,
  "density.css": renderDensityCss,
  "domain.css": renderDomainCss,
} as const;
